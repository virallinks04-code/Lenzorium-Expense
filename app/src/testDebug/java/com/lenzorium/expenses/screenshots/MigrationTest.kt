package com.lenzorium.expenses.screenshots

import android.content.Context
import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.lenzorium.expenses.data.AppDatabase
import com.lenzorium.expenses.data.TxnType
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.annotation.Config

/**
 * Upgrading from the first release (database version 1, no accounts) must keep every record
 * and assign it to Cash or Bank. Builds a real version-1 database file and opens it with the new app.
 */
@RunWith(AndroidJUnit4::class)
@Config(sdk = [35])
class MigrationTest {
    @Test
    fun version1DatabaseUpgradesWithoutLosingData() {
        val ctx = ApplicationProvider.getApplicationContext<Context>()
        val name = "migration-test.db"
        ctx.deleteDatabase(name)
        val file = ctx.getDatabasePath(name).apply { parentFile?.mkdirs() }

        SQLiteDatabase.openOrCreateDatabase(file, null).use { db ->
            // Exact schema of version 1 (as generated by Room for the first release).
            db.execSQL("CREATE TABLE IF NOT EXISTS `transactions` (`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, `type` TEXT NOT NULL, `amountMinor` INTEGER NOT NULL, `categoryId` INTEGER, `timestamp` INTEGER NOT NULL, `party` TEXT NOT NULL, `paymentMethod` TEXT, `notes` TEXT NOT NULL, `receiptFile` TEXT, `loanId` INTEGER, `requestId` TEXT NOT NULL, `createdAt` INTEGER NOT NULL)")
            db.execSQL("CREATE INDEX IF NOT EXISTS `index_transactions_loanId` ON `transactions` (`loanId`)")
            db.execSQL("CREATE INDEX IF NOT EXISTS `index_transactions_timestamp` ON `transactions` (`timestamp`)")
            db.execSQL("CREATE UNIQUE INDEX IF NOT EXISTS `index_transactions_requestId` ON `transactions` (`requestId`)")
            db.execSQL("CREATE TABLE IF NOT EXISTS `loans` (`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, `lender` TEXT NOT NULL, `title` TEXT NOT NULL, `principalMinor` INTEGER NOT NULL, `receivedAt` INTEGER NOT NULL, `dueEpochDay` INTEGER, `notes` TEXT NOT NULL, `isOpening` INTEGER NOT NULL, `requestId` TEXT NOT NULL, `createdAt` INTEGER NOT NULL)")
            db.execSQL("CREATE UNIQUE INDEX IF NOT EXISTS `index_loans_requestId` ON `loans` (`requestId`)")
            db.execSQL("CREATE TABLE IF NOT EXISTS `categories` (`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, `name` TEXT NOT NULL, `kind` TEXT NOT NULL, `iconKey` TEXT NOT NULL, `colorArgb` INTEGER NOT NULL, `isFallback` INTEGER NOT NULL, `sortOrder` INTEGER NOT NULL)")

            db.execSQL("INSERT INTO categories VALUES (1,'Food','EXPENSE','food',4293154606,0,1)")
            db.execSQL("INSERT INTO loans VALUES (1,'Ali','',3000000,1000,NULL,'',0,'l1',0)")
            db.execSQL("INSERT INTO transactions VALUES (1,'EXPENSE',125000,1,2000,'Shop','CASH','',NULL,NULL,'r1',0)")
            db.execSQL("INSERT INTO transactions VALUES (2,'EXPENSE',50000,1,3000,'Online','CARD','',NULL,NULL,'r2',0)")
            db.execSQL("INSERT INTO transactions VALUES (3,'LOAN_RECEIVED',3000000,NULL,1000,'Ali','BANK','',NULL,1,'r3',0)")
            db.execSQL("INSERT INTO transactions VALUES (4,'LOAN_CHARGE',10000,NULL,4000,'Ali',NULL,'',NULL,1,'r4',0)")
            db.version = 1
        }

        val room = Room.databaseBuilder(ctx, AppDatabase::class.java, name)
            .addMigrations(AppDatabase.MIGRATION_1_2)
            .allowMainThreadQueries()
            .build()
        runBlocking {
            val dao = room.dao()
            val accounts = dao.allAccounts()
            assertEquals(listOf("Cash", "Bank"), accounts.map { it.name })
            val txns = dao.allTxns().associateBy { it.id }
            assertEquals(4, txns.size)
            assertEquals(AppDatabase.CASH_ID, txns[1]!!.accountId)   // Cash stays Cash
            assertEquals(AppDatabase.BANK_ID, txns[2]!!.accountId)   // Card payments come from the Bank
            assertEquals(AppDatabase.BANK_ID, txns[3]!!.accountId)
            assertNull(txns[4]!!.accountId)                           // loan charges don't touch any account
            assertEquals(TxnType.LOAN_CHARGE, txns[4]!!.type)
            assertEquals(125000L, txns[1]!!.amountMinor)
            assertEquals(1, dao.allLoans().size)
            assertEquals(1, dao.allCategories().size)
        }
        room.close()
    }
}
